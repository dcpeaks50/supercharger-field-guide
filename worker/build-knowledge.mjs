// Builds worker/knowledge.js: the study guide content + the V4-relevant source text Claude answers from.
// usage: node build-knowledge.mjs <dir with extracted source .txt files>
import fs from "node:fs";
import path from "node:path";
const here = import.meta.dirname;
const srcDir = process.argv[2];
const html = fs.readFileSync(path.join(here, "..", "index.html"), "utf8");

const strip = (s) => s.replace(/<[^>]+>/g, " ").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&apos;/g, "'").replace(/\$\{S\.(\w+)\}/g, "$1").replace(/[ \t]+/g, " ").replace(/\n\s*\n+/g, "\n").trim();

// Study guide topics (title, lede, body).
const topics = [...html.matchAll(/\{ id:"(\w+)", title:"([^"]+)", lede:"([^"]+)", html:`([\s\S]*?)` \},?/g)]
  .map(([, , title, lede, body]) => `## ${title}\n${lede}\n${strip(body)}`).join("\n\n");

// Flashcards as Q/A pairs.
const cards = [...html.matchAll(/\["\w+",\d,"([^"]+)","([^"]+)","([^"]+)"\],/g)].map(([, q, a, src]) => `Q: ${q} A: ${a} (${src})`).join("\n");

// Source documents: V4-relevant only (skip the V3 cabinet and V3-based PSU chapters of the design manual).
const read = (f) => fs.readFileSync(path.join(srcDir, f), "utf8");
const clean = (t) => t.split("\n").map((l) => l.replace(/\s+/g, " ").trim()).filter((l) => l.length > 1).join("\n");
const manual = read("ssdg-clean.txt").split(/\n(?=## p\d+\n)/).filter((block) => {
  const n = +(/^## p(\d+)/.exec(block)?.[1] ?? 0);
  return !(n >= 42 && n <= 72) && !(n >= 90 && n <= 113);
}).join("\n").replace(/^## p(\d+)$/gm, "[Design Manual p.$1]");
const semi = clean(read("V4 Semi Charger Site Design Guide (1).txt")).replace(/PROPRIETARY AND CONFIDENTIAL[\s\S]*?TESLA SEMICHARGER DESIGN GUIDE/g, "");
const docs = [
  ["V4 Cabinet datasheet", clean(read("V4 Cabinet Datasheet.txt"))],
  ["V4 Post datasheet", clean(read("Tesla_V4_Post_Supercharger_Datasheet 2 (2).txt"))],
  ["V4 Semi Post datasheet", clean(read("V4 Semi MCS Post Data Sheet (1).txt"))],
  ["Semicharger Design Guide (uses the V4 cabinet)", semi],
  ["Construction Quality Checklist", clean(read("Supercharger Sales Commissioning Construction Quality Checklist (1) (1).txt"))],
  ["Site Survey Checklist", clean(read("Tesla Supercharger Site Survey Checklist.txt")).replace(/For engineering questions call[^\n]*/g, "")],
];

const knowledge = [
  "# STUDY GUIDE (curated summary)\n" + topics,
  "# FLASHCARDS\n" + cards,
  "# SOURCE: Commercial Charging Design Manual (V4-relevant chapters)\n" + manual,
  ...docs.map(([name, text]) => `# SOURCE: ${name}\n${text}`),
].join("\n\n");

fs.writeFileSync(path.join(here, "knowledge.js"), `// Generated by build-knowledge.mjs. Do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(knowledge)};\n`);
console.log(`knowledge: ${Math.round(knowledge.length / 1000)}k chars (~${Math.round(knowledge.length / 4000)}k tokens)`);
